"""Rebuild data/codes/*.yaml from a saved copy of the NHS Data Dictionary page
'Main Specialty and Treatment Function Codes Table':
https://www.datadictionary.nhs.uk/supporting_information/main_specialty_and_treatment_function_codes_table.html

Usage (from nhs-specialties/):
    python3 ingest/ingest_dd_table.py [saved-page.html] [--retrieved YYYY-MM-DD]

With no page given it reads the newest copy in source/. To update: save the
live page (browser "Save page as... HTML") into source/ as
dd-main-specialty-and-treatment-function-codes-table.<YYYY-MM-DD>.html,
re-run this script, then run the tests: they report any factsheet that now
points at a retired or vanished code.

The page holds two independent lists, Table 1 (Main Specialty Codes) and Table 2
(Treatment Function Codes), each grouped under headings. It does not map one to
the other. Table 2 also lists codes that are *not* treatment functions (e.g. 823
Haematology, "See Clinical Haematology"); those are kept in
treatment-functions.yaml under not_treatment_functions.
Standard library only.
"""
import argparse, html, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'data', 'codes')
URL = 'https://www.datadictionary.nhs.uk/supporting_information/main_specialty_and_treatment_function_codes_table.html'


def clean(fragment):
    text = re.sub(r'<[^>]+>', ' ', fragment)
    return html.unescape(re.sub(r'\s+', ' ', text)).strip()


def tables(page):
    """[(caption_text_before_table, [[cell, ...], ...]), ...]"""
    out = []
    for pre, table in re.findall(r'(.{0,400})(<table.*?</table>)', page, flags=re.S):
        rows = [[clean(c) for c in re.findall(r'<t[hd][^>]*>(.*?)</t[hd]>', tr, flags=re.S)]
                for tr in re.findall(r'<tr.*?</tr>', table, flags=re.S)]
        out.append((clean(pre), rows))
    return out


def find(tabs, caption):
    for pre, rows in tabs:
        if pre.endswith(caption):
            return rows
    sys.exit(f'could not find "{caption}" in the page - has its layout changed?')


def coded_rows(rows):
    """Yield (heading, code, flag, title, comment). Heading rows have one cell."""
    heading = None
    for r in rows[1:]:
        if len(r) == 1:
            # the children's heading carries a long explanation after ' - '
            heading = r[0].split(' - ')[0].strip()
            continue
        i = next((k for k, c in enumerate(r) if re.match(r'^\d{3}\b', c)), None)
        if i is None:
            continue
        code = r[i][:3]
        flag = (r[i][3:].strip() + ''.join(r[:i])).strip()
        title = r[i + 1] if len(r) > i + 1 else ''
        comment = r[i + 2] if len(r) > i + 2 else ''
        yield heading, code, flag, title, comment


RETIRED = re.compile(r'\s*\(Retired ([^)]*)\)\s*$')


def q(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('page', nargs='?', help='saved copy of the page (default: newest in source/)')
    ap.add_argument('--retrieved', default=None, help='date the page copy was taken (default: from the file name)')
    a = ap.parse_args()
    if not a.page:
        src = os.path.join(HERE, '..', 'source')
        copies = sorted(f for f in os.listdir(src) if f.startswith('dd-main-specialty-and-treatment-function-codes-table.'))
        if not copies: sys.exit('no saved copy in source/')
        a.page = os.path.join(src, copies[-1])
    if not a.retrieved:
        m = re.search(r'(\d{4}-\d{2}-\d{2})\.html?$', a.page)
        a.retrieved = m.group(1) if m else None
    print('reading', os.path.relpath(a.page))
    page = open(a.page, encoding='utf-8', errors='replace').read()
    tabs = tables(page)
    footnotes = {}
    for _, rows in tabs:
        for r in rows:
            if len(r) == 2 and r[0] in ('†', '*'):
                footnotes[r[0]] = r[1]

    stamp = f'# Source: {URL}\n' + (f'# Copy of the page retrieved {a.retrieved}.\n' if a.retrieved else '') + \
        '# Generated by ingest/ingest_dd_table.py - do not edit by hand; re-run the script.\n'

    # ---- Table 1: main specialties
    ms = []
    for heading, code, flag, title, comment in coded_rows(find(tabs, 'Table 1 Main Specialty Codes')):
        m = RETIRED.search(title)
        rec = {'code': code, 'title': RETIRED.sub('', title), 'heading': heading,
               'status': 'retired' if m else 'active'}
        if m: rec['retired'] = m.group(1)
        if comment: rec['comment'] = comment
        if flag in footnotes: rec['footnote'] = footnotes[flag]
        ms.append(rec)

    # ---- Table 2: treatment functions (and the codes it says are not treatment functions)
    tfc, not_tfc = [], []
    for heading, code, flag, title, comment in coded_rows(find(tabs, 'Table 2 Treatment Function Codes')):
        if title.lower() == 'not a treatment function':
            rec = {'code': code}
            if comment: rec['comment'] = comment
            not_tfc.append(rec)
            continue
        retired = title.lower().startswith('retired')
        rec = {'code': code, 'title': 'Retired' if retired else title, 'heading': heading,
               'status': 'retired' if retired else 'active'}
        if comment: rec['comment'] = comment
        if flag in footnotes: rec['footnote'] = footnotes[flag]
        tfc.append(rec)

    def dump(path, header, sections):
        lines = [header]
        for key, recs in sections:
            lines.append(f'{key}:')
            for r in recs:
                first = True
                for k, v in r.items():
                    lines.append(f'  {"- " if first else "  "}{k}: {q(v)}')
                    first = False
        with open(path, 'w') as f:
            f.write('\n'.join(lines) + '\n')

    dump(os.path.join(OUT, 'main-specialties.yaml'),
         '# NHS Data Dictionary - Table 1, MAIN SPECIALTY CODE national codes.\n' + stamp +
         '# A main specialty is a specialty recognised by the Royal Colleges / Faculties;\n'
         '# it describes the consultant (or other lead), not the service.\n',
         [('codes', ms)])
    dump(os.path.join(OUT, 'treatment-functions.yaml'),
         '# NHS Data Dictionary - Table 2, TREATMENT FUNCTION CODE national codes.\n' + stamp +
         '# A treatment function is the specialised service a patient is treated in.\n'
         '# not_treatment_functions: codes Table 2 lists as "not a Treatment Function"\n'
         '# (main-specialty-only codes), with the Data Dictionary comment where it gives one.\n',
         [('codes', tfc), ('not_treatment_functions', not_tfc)])
    print(f'{len(ms)} main specialty codes ({sum(r["status"] == "retired" for r in ms)} retired), '
          f'{len(tfc)} treatment function codes ({sum(r["status"] == "retired" for r in tfc)} retired), '
          f'{len(not_tfc)} not-a-treatment-function codes')


if __name__ == '__main__':
    main()
